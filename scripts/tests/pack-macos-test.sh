#!/usr/bin/env bash
# 用隔离仓库和命令桩验证打包流程；不生成或校验真实 macOS App、签名或 DMG。
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TEST_ROOT="$(mktemp -d "${TMPDIR:-/tmp}/pi-bot-pack-test.XXXXXX")"
TEST_ROOT="$(cd "$TEST_ROOT" && pwd)"
trap 'rm -rf -- "$TEST_ROOT"' EXIT
FIXTURE="$TEST_ROOT/repo with spaces and 'quote'"
STUBS="$TEST_ROOT/stubs"
TRACE="$TEST_ROOT/trace"
REAL_NODE="$(command -v node)"
REAL_MV="$(command -v mv)"
export FIXTURE TRACE REAL_NODE REAL_MV
mkdir -p "$FIXTURE/scripts" "$FIXTURE/server/src" "$FIXTURE/server/tools" "$STUBS"
cp "$ROOT/scripts/pack-macos.sh" "$FIXTURE/scripts/pack-macos.sh"
mkdir -p "$FIXTURE/app/macos/Runner"
printf '<plist><dict/></plist>\n' > "$FIXTURE/app/macos/Runner/Release.entitlements"
printf '{"name":"fixture","version":"0.1.0","dependencies":{}}\n' > "$FIXTURE/server/package.json"
printf '{"lockfileVersion":3}\n' > "$FIXTURE/server/package-lock.json"
printf 'fixture server version one\n' > "$FIXTURE/server/src/index.js"
printf 'fixture tool\n' > "$FIXTURE/server/tools/check.mjs"
printf 'FIXTURE=1\n' > "$FIXTURE/server/.env.example"
BUILD="$FIXTURE/app/build/macos/Build/Products/Release"
mkdir -p "$BUILD/pi_bot.app/Contents/MacOS"
printf '<plist><dict/></plist>\n' > "$BUILD/pi_bot.app/Contents/Info.plist"
printf 'fixture executable\n' > "$BUILD/pi_bot.app/Contents/MacOS/pi_bot"
printf 'fallback product\n' > "$BUILD/pi_bot.app/Contents/product.txt"
mkdir -p "$FIXTURE/dist"
printf 'preserve this file\n' > "$FIXTURE/dist/user-note.txt"
printf 'preserve another version\n' > "$FIXTURE/dist/pi-bot-other.dmg"

cat > "$STUBS/dispatch" <<'STUB'
#!/usr/bin/env bash
set -euo pipefail
tool="${0##*/}"
printf '%s' "$tool" >> "$TRACE"
printf ' %q' "$@" >> "$TRACE"
printf '\n' >> "$TRACE"
case "$tool" in
  uname) printf '%s\n' "${PACK_PLATFORM:-Darwin}" ;;
  node)
    if [[ "${PACK_NODE_OLD:-0}" == 1 ]]; then
      [[ "${1:-}" == --version ]] && { printf 'v20.0.0\n'; exit 0; }
      exit 1
    fi
    exec "$REAL_NODE" "$@"
    ;;
  npm)
    [[ "${PACK_FAIL:-}" != npm ]] || exit 31
    [[ "$*" == 'install --omit=dev --no-audit --no-fund' ]]
    [[ "$PWD" == */pi-bot.app/Contents/Resources/server ]]
    mkdir -p node_modules
    if [[ ! -f package-lock.json ]]; then
      printf '{"fixture":"generated by npm stub"}\n' > package-lock.json
    fi
    ;;
  ditto)
    [[ "${PACK_FAIL:-}" != copy ]] || exit 32
    if [[ -d "$1" ]]; then
      mkdir -p "$2"
      cp -R "$1/." "$2/"
    else
      cp "$1" "$2"
    fi
    ;;
  codesign)
    if [[ "$1" == --verify ]]; then
      [[ "${PACK_FAIL:-}" != signature-verify ]] || exit 33
      [[ -f "${@: -1}/Contents/fixture-signature" ]]
    else
      [[ "${PACK_FAIL:-}" != sign ]] || exit 34
      [[ "$*" == *'--entitlements '* ]]
      printf 'fixture signature\n' > "${@: -1}/Contents/fixture-signature"
    fi
    ;;
  hdiutil)
    if [[ "$1" == create ]]; then
      [[ "${PACK_FAIL:-}" != dmg-create ]] || exit 35
      payload=''
      while [[ $# -gt 0 ]]; do
        if [[ "$1" == -srcfolder ]]; then payload="$2"; shift; fi
        target="$1"
        shift
      done
      [[ -d "$payload/pi-bot.app" && ! -e "$payload/Contents" ]]
      [[ -L "$payload/Applications" && "$(readlink "$payload/Applications")" == /Applications ]]
      server="$payload/pi-bot.app/Contents/Resources/server"
      for item in src/index.js tools/check.mjs package.json package-lock.json .env.example node_modules; do
        [[ -e "$server/$item" ]]
      done
      printf 'STUB DMG: not a disk image\n' > "$target"
      cat "$server/src/index.js" >> "$target"
    else
      [[ "$1" == verify ]]
      [[ "${PACK_FAIL:-}" != dmg-verify ]] || exit 36
      [[ -f "$2" && "$(head -n 1 "$2")" == 'STUB DMG: not a disk image' ]]
    fi
    ;;
  xattr) [[ "$1" == -dr && "$2" == com.apple.quarantine ]] ;;
  xcodebuild) [[ "${PACK_FAIL:-}" != xcode ]] || exit 37 ;;
  xcrun) [[ "${PACK_FAIL:-}" != sdk ]] || exit 38 ;;
  flutter) [[ "${PACK_FAIL:-}" != build ]] || exit 39 ;;
  mv)
    if [[ "${PACK_FAIL:-}" == publish-app && "$1" == */payload/pi-bot.app ]]; then exit 40; fi
    if [[ "${PACK_FAIL:-}" == publish-dmg && "$1" == */.pack-macos.*/pi-bot-0.1.0.dmg ]]; then exit 41; fi
    if [[ "${PACK_FAIL:-}" == backup-dmg && "$1" == "$FIXTURE/dist/pi-bot-0.1.0.dmg" ]]; then exit 42; fi
    exec "$REAL_MV" "$@"
    ;;
  *) exit 99 ;;
esac
STUB
chmod +x "$STUBS/dispatch" "$FIXTURE/scripts/pack-macos.sh"
for tool in uname node npm ditto codesign hdiutil xattr xcodebuild xcrun flutter mv; do
  ln -s dispatch "$STUBS/$tool"
done
export PATH="$STUBS:$PATH"
PASS=0

die() {
  echo "FAIL: $*" >&2
  cat "$TEST_ROOT/run.log" >&2
  exit 1
}

ok() {
  PASS=$((PASS + 1))
  printf 'PASS: %s\n' "$*"
}

run_ok() {
  : > "$TRACE"
  "$FIXTURE/scripts/pack-macos.sh" "$@" > "$TEST_ROOT/run.log" 2>&1 \
    || die "命令应成功：$*"
}

run_fail() {
  : > "$TRACE"
  if "$FIXTURE/scripts/pack-macos.sh" "$@" > "$TEST_ROOT/run.log" 2>&1; then
    die "命令应失败：$*"
  fi
}

no_stage() {
  local stages
  shopt -s nullglob
  stages=("$FIXTURE/dist"/.pack-macos.*)
  [[ ${#stages[@]} -eq 0 ]] || die '暂存目录未清理'
}

preserved() {
  cmp "$TEST_ROOT/expected-app" "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/src/index.js" \
    || die '旧 App 被破坏'
  cmp "$TEST_ROOT/expected-dmg" "$FIXTURE/dist/pi-bot-0.1.0.dmg" || die '旧 DMG 被破坏'
  [[ "$(cat "$FIXTURE/dist/user-note.txt")" == 'preserve this file' ]] || die '其他文件被破坏'
  [[ "$(cat "$FIXTURE/dist/pi-bot-other.dmg")" == 'preserve another version' ]] || die '其他版本被破坏'
  no_stage
}

echo '命令桩测试：不代表真实 App、签名或 DMG 已通过验证。'
run_ok --help
[[ ! -s "$TRACE" ]] || die '帮助触发了工具调用'
ok '帮助不要求构建环境'
run_fail --unknown
[[ ! -s "$TRACE" ]] || die '未知参数触发了工具调用'
ok '未知参数被拒绝'
PACK_PLATFORM=Linux run_fail --no-build
ok '非 macOS 被拒绝'
PACK_NODE_OLD=1 run_fail --no-build
ok 'Node 22 以下被拒绝'

PACK_FAIL=xcode run_ok --no-build
[[ "$(cat "$FIXTURE/dist/pi-bot.app/Contents/product.txt")" == 'fallback product' ]] || die '未采用兼容产品名'
if grep -Eq '^(flutter|xcodebuild|xcrun|xattr) ' "$TRACE"; then die '--no-build 或默认隔离属性行为错误'; fi
ok '含空格与单引号路径可打包，兼容 pi_bot.app；--no-build 跳过 Xcode，默认不清隔离属性'
cmp "$FIXTURE/server/package-lock.json" "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/package-lock.json" \
  || die '已有锁文件未正确复制到安装目录'
ok '已有锁文件正确复制后供生产依赖安装使用'
cp "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/src/index.js" "$TEST_ROOT/expected-app"
cp "$FIXTURE/dist/pi-bot-0.1.0.dmg" "$TEST_ROOT/expected-dmg"
run_ok --no-build
preserved
ok '重复执行且保留 dist 中其他文件与版本'

mkdir -p "$BUILD/pi-bot.app"
cp -R "$BUILD/pi_bot.app/." "$BUILD/pi-bot.app/"
printf 'preferred product\n' > "$BUILD/pi-bot.app/Contents/product.txt"
run_ok --no-build
[[ "$(cat "$FIXTURE/dist/pi-bot.app/Contents/product.txt")" == 'preferred product' ]] || die '未优先采用 pi-bot.app'
ok '两种构建名称并存时优先 pi-bot.app'
run_ok --clear-quarantine --no-build
[[ "$(grep -c '^xattr ' "$TRACE")" == 2 ]] || die '未显式清理 App 与 DMG 隔离属性'
ok '参数可交换顺序，清隔离属性仅在显式开启时执行'

printf 'fixture server version two\n' > "$FIXTURE/server/src/index.js"
for failure in copy npm sign signature-verify dmg-create dmg-verify backup-dmg publish-app publish-dmg; do
  PACK_FAIL="$failure" run_fail --no-build
  preserved
  ok "$failure 失败保留旧 App、旧 DMG 与其他 dist 文件"
done

for failure in xcode sdk build; do
  PACK_FAIL="$failure" run_fail
  preserved
  if [[ "$failure" != build ]] && grep -q '^flutter ' "$TRACE"; then die 'Xcode 预检失败仍调用构建'; fi
  ok "$failure 失败保留旧成品且不绕过构建预检"
done

mv "$FIXTURE/server/package-lock.json" "$FIXTURE/server/missing-lock"
run_ok --no-build
[[ ! -e "$FIXTURE/server/package-lock.json" ]] || die '安装将锁文件写回了源仓库'
grep -q 'generated by npm stub' "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/package-lock.json" \
  || die '无锁文件时未在 App 内完成安装'
cmp "$FIXTURE/server/src/index.js" "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/src/index.js" \
  || die '无锁文件时未发布本轮服务端内容'
no_stage
mv "$FIXTURE/server/missing-lock" "$FIXTURE/server/package-lock.json"
cp "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/src/index.js" "$TEST_ROOT/expected-app"
cp "$FIXTURE/dist/pi-bot-0.1.0.dmg" "$TEST_ROOT/expected-dmg"
ok '无仓库锁文件正常安装并打包，生成的锁仅留在 App 内'

cp "$FIXTURE/server/package.json" "$TEST_ROOT/package.json"
printf '{"version":"0.1.0","dependencies":{"fixture-missing-package":"1.0.0"}}\n' > "$FIXTURE/server/package.json"
run_fail --no-build
preserved
cp "$TEST_ROOT/package.json" "$FIXTURE/server/package.json"
ok '安装命令成功但缺少声明依赖时失败且保留旧成品'

printf '{"version":"../invalid","dependencies":{}}\n' > "$FIXTURE/server/package.json"
run_fail --no-build
preserved
cp "$TEST_ROOT/package.json" "$FIXTURE/server/package.json"
ok '拒绝版本路径穿越'

run_ok
grep -q '^xcodebuild ' "$TRACE" || die '正常构建未检查 Xcode'
grep -q '^xcrun ' "$TRACE" || die '正常构建未检查 SDK'
grep -q '^flutter build macos --release$' "$TRACE" || die '正常构建未调用 Flutter'
cmp "$FIXTURE/server/src/index.js" "$FIXTURE/dist/pi-bot.app/Contents/Resources/server/src/index.js" \
  || die '未发布本轮服务端内容'
no_stage
ok '正常构建走 Xcode 与 SDK 预检并发布完整 payload'
printf '%s 项命令桩测试通过（真实 macOS 构建需另行验证）。\n' "$PASS"
